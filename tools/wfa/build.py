"""data/ + addon/ -> out/dist/WoWFA (+ zip). Deterministic: same inputs, same bytes."""
import os
import shutil
import zipfile

from .core import OUT, ROOT, lua_str
from .resolve import resolve
from .store import QUEST_FIELDS

HEAD = ("-- generated by tools/ci.py build from data/ - never edit by hand\n"
        "WoWFA_FData = WoWFA_FData or {}\nlocal D = WoWFA_FData\n")


def quest_record(rec, names):
    return "\x1f".join(resolve(rec.get(f, ""), names) if f != "h" else rec.get("h", "")
                       for f in QUEST_FIELDS)


def quest_pack(rows):
    """1.1.6 RAM (the owner: "the addon takes much more memory than the others"): the quest
    texts were 8.4 of the 12.3 MB. Every non-ASCII character of the rows becomes ONE byte
    (0x80-0xFE, the 127 most frequent: D.qmap) or two (0xFF + byte: D.qrare) instead of 2-3
    UTF-8 bytes. ASCII (markers, $N, digits, the hash) is kept, so the hash prefix and the
    field split still work on the packed row. F.QRow (Core.lua) unpacks. Deterministic."""
    from collections import Counter
    freq = Counter(ch for r in rows for ch in r if ord(ch) > 127)
    order = sorted(freq, key=lambda c: (-freq[c], ord(c)))
    if len(order) > 254:
        raise ValueError("quest texts: %d distinct non-ASCII characters (the packing holds 254)" % len(order))
    single, rare = order[:127], order[127:]
    code = {c: bytes([0x80 + i]) for i, c in enumerate(single)}
    code.update({c: b"\xff" + bytes([0x80 + i]) for i, c in enumerate(rare)})
    return single, rare, code


def lua_packed(s, code):
    """A Lua 5.1 literal of a packed row: raw packed bytes, the same escapes as lua_str."""
    out = bytearray(b'"')
    for ch in s:
        o = ord(ch)
        if o > 127:
            out += code[ch]
        elif ch == "\\":
            out += b"\\\\"
        elif ch == '"':
            out += b'\\"'
        elif ch == "\n":
            out += b"\\n"
        elif o < 32 or o == 127:
            out += b"\\%03d" % o
        else:
            out.append(o)
    out += b'"'
    return bytes(out)


def emit_data(store, policy, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    counts = {}
    ship = policy["ship"]["names"]
    # Names.lua: shipped kinds only
    parts = [HEAD, "D.names = {\n"]
    for kind in sorted(ship):
        table = store.names.get(kind, {})
        counts["names." + kind] = len(table)
        parts.append("%s = {\n" % kind)
        for k in sorted(table):
            parts.append("[%s]=%s,\n" % (lua_str(k), lua_str(table[k])))
        parts.append("},\n")
    parts.append("}\n")
    _write(os.path.join(out_dir, "Names.lua"), "".join(parts))
    # Quests.lua
    rows = {qid: quest_record(store.quests[qid], store.names) for qid in sorted(store.quests)}
    single, rare, code = quest_pack(list(rows.values()))
    q = [HEAD.encode("utf-8"),
         b"-- 1.1.6: the rows are packed (one byte per Persian character); F.QRow unpacks\n",
         b"D.qmap = {" + b",".join(lua_str(c).encode("utf-8") for c in single) + b"}\n",
         b"D.qrare = {" + b",".join(lua_str(c).encode("utf-8") for c in rare) + b"}\n",
         b"D.quests = {\n"]
    o = ["D.qobj = {\n"]
    nobj = 0
    for qid in sorted(store.quests):
        rec = store.quests[qid]
        q.append(b"[%d]=%s,\n" % (qid, lua_packed(rows[qid], code)))
        if rec.get("o"):
            nobj += 1
            o.append("[%d]={%s},\n" % (qid, ",".join(lua_str(resolve(x, store.names)) for x in rec["o"])))
    q.append(b"}\n")
    o.append("}\n")
    counts["quests"] = len(store.quests)
    counts["qobj"] = nobj
    path = os.path.join(out_dir, "Quests.lua")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(b"".join(q) + "".join(o).encode("utf-8"))
    # Tpl.lua
    t = [HEAD, "D.tpl = {\n"]
    for k in sorted(store.tpl):
        t.append("[%s]=%s,\n" % (lua_str(k), lua_str(resolve(store.tpl[k], store.names))))
    t.append("}\n")
    counts["tpl"] = len(store.tpl)
    _write(os.path.join(out_dir, "Tpl.lua"), "".join(t))
    # Strings.lua (panel / UI Persian)
    s = [HEAD, "D.ui = {\n"]
    for k in sorted(store.ui):
        s.append("[%s]=%s,\n" % (lua_str(k), lua_str(store.ui[k])))
    s.append("}\n")
    _write(os.path.join(out_dir, "Strings.lua"), "".join(s))
    # Meta.lua last: the counts of what was really written
    build_num = int(str(policy["game_build"]).split(".")[-1])
    meta = [HEAD, "D.meta = { schema = 2, version = %s, build = %s, buildNum = %d, counts = {\n"
            % (lua_str(policy["version"]), lua_str(policy["game_build"]), build_num)]
    for k in sorted(counts):
        meta.append("[%s]=%d,\n" % (lua_str(k), counts[k]))
    meta.append("} }\n")
    _write(os.path.join(out_dir, "Meta.lua"), "".join(meta))
    return counts


def build(store, policy):
    dist = os.path.join(OUT, "dist")
    if os.path.isdir(dist):
        shutil.rmtree(dist)
    addon_src = os.path.join(ROOT, "addon", "WoWFA")
    dst = os.path.join(dist, "WoWFA")
    notes = []
    if os.path.isdir(addon_src):
        shutil.copytree(addon_src, dst, ignore=shutil.ignore_patterns("*.in", ".*"))
        for fn in sorted(os.listdir(addon_src)):
            if not fn.endswith(".toc.in"):
                continue
            with open(os.path.join(addon_src, fn), encoding="utf-8") as f:
                toc = f.read()
            toc = toc.replace("@VERSION@", policy["version"]).replace("@INTERFACE@", str(policy["interface"]))
            _write(os.path.join(dst, fn[:-3]), toc)
    else:
        notes.append("addon/WoWFA not present yet: data-only build")
    counts = emit_data(store, policy, os.path.join(dst, "Data"))
    zpath = os.path.join(OUT, "WoWFA-%s.zip" % policy["version"])
    if os.path.exists(zpath):
        os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(dist):
            for fn in sorted(files):
                full = os.path.join(base, fn)
                info = zipfile.ZipInfo(os.path.relpath(full, dist).replace(os.sep, "/"), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                with open(full, "rb") as f:
                    z.writestr(info, f.read())
    return counts, zpath, notes


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
