"""data/ + addon/ -> out/dist/WoWFA (+ zip). Deterministic: same inputs, same bytes."""
import os
import shutil
import zipfile

from .core import OUT, ROOT, lua_str
from .resolve import resolve
from .store import QUEST_FIELDS

HEAD = ("-- generated by tools/ci.py build from data/ - never edit by hand\n"
        "WoWFA_FData = WoWFA_FData or {}\nlocal D = WoWFA_FData\n")


def quest_record(rec, names):
    return "\x1f".join(resolve(rec.get(f, ""), names) if f != "h" else rec.get("h", "")
                       for f in QUEST_FIELDS)


def emit_data(store, policy, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    counts = {}
    ship = policy["ship"]["names"]
    # Names.lua: shipped kinds only
    parts = [HEAD, "D.names = {\n"]
    for kind in sorted(ship):
        table = store.names.get(kind, {})
        counts["names." + kind] = len(table)
        parts.append("%s = {\n" % kind)
        for k in sorted(table):
            parts.append("[%s]=%s,\n" % (lua_str(k), lua_str(table[k])))
        parts.append("},\n")
    parts.append("}\n")
    _write(os.path.join(out_dir, "Names.lua"), "".join(parts))
    # Quests.lua
    q = [HEAD, "D.quests = {\n"]
    o = ["D.qobj = {\n"]
    nobj = 0
    for qid in sorted(store.quests):
        rec = store.quests[qid]
        q.append("[%d]=%s,\n" % (qid, lua_str(quest_record(rec, store.names))))
        if rec.get("o"):
            nobj += 1
            o.append("[%d]={%s},\n" % (qid, ",".join(lua_str(resolve(x, store.names)) for x in rec["o"])))
    q.append("}\n")
    o.append("}\n")
    counts["quests"] = len(store.quests)
    counts["qobj"] = nobj
    _write(os.path.join(out_dir, "Quests.lua"), "".join(q) + "".join(o))
    # Tpl.lua
    t = [HEAD, "D.tpl = {\n"]
    for k in sorted(store.tpl):
        t.append("[%s]=%s,\n" % (lua_str(k), lua_str(resolve(store.tpl[k], store.names))))
    t.append("}\n")
    counts["tpl"] = len(store.tpl)
    _write(os.path.join(out_dir, "Tpl.lua"), "".join(t))
    # Strings.lua (panel / UI Persian)
    s = [HEAD, "D.ui = {\n"]
    for k in sorted(store.ui):
        s.append("[%s]=%s,\n" % (lua_str(k), lua_str(store.ui[k])))
    s.append("}\n")
    _write(os.path.join(out_dir, "Strings.lua"), "".join(s))
    # Meta.lua last: the counts of what was really written
    meta = [HEAD, "D.meta = { schema = 2, version = %s, build = %s, counts = {\n"
            % (lua_str(policy["version"]), lua_str(policy["game_build"]))]
    for k in sorted(counts):
        meta.append("[%s]=%d,\n" % (lua_str(k), counts[k]))
    meta.append("} }\n")
    _write(os.path.join(out_dir, "Meta.lua"), "".join(meta))
    return counts


def build(store, policy):
    dist = os.path.join(OUT, "dist")
    if os.path.isdir(dist):
        shutil.rmtree(dist)
    addon_src = os.path.join(ROOT, "addon", "WoWFA")
    dst = os.path.join(dist, "WoWFA")
    notes = []
    if os.path.isdir(addon_src):
        shutil.copytree(addon_src, dst, ignore=shutil.ignore_patterns("*.in", ".*"))
        toc_in = os.path.join(addon_src, "WoWFA.toc.in")
        if os.path.exists(toc_in):
            with open(toc_in, encoding="utf-8") as f:
                toc = f.read()
            toc = toc.replace("@VERSION@", policy["version"]).replace("@INTERFACE@", str(policy["interface"]))
            _write(os.path.join(dst, "WoWFA.toc"), toc)
    else:
        notes.append("addon/WoWFA not present yet: data-only build")
    counts = emit_data(store, policy, os.path.join(dst, "Data"))
    zpath = os.path.join(OUT, "WoWFA-%s.zip" % policy["version"])
    if os.path.exists(zpath):
        os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(dist):
            for fn in sorted(files):
                full = os.path.join(base, fn)
                info = zipfile.ZipInfo(os.path.relpath(full, dist).replace(os.sep, "/"), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                with open(full, "rb") as f:
                    z.writestr(info, f.read())
    return counts, zpath, notes


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
